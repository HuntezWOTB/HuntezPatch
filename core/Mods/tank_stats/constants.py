    """Stats column block for the given project.

    WG keeps the proven StatisticsHolder block; Lesta uses the TankStats
    block (inner-TankInfo sibling, _s icons, old-text colors, lifted by
    half a digit) proven in-game on the Lesta client.
    """
    if (project or "wargaming").lower() == "lesta":
        return list(TANKSTATS_BLOCK_LESTA)
    return list(TANKSTATS_BLOCK)


